// Regenerate shared/generated/ts/index.ts from shared/schemas/ (json-schema-to-typescript).
// All schemas compile through one bundled root so shared types are emitted once.
import { mkdir, readdir, writeFile } from 'node:fs/promises';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compile } from 'json-schema-to-typescript';

const root = fileURLToPath(new URL('..', import.meta.url));
const schemaDir = join(root, 'shared/schemas');
const outDir = join(root, 'shared/generated/ts');

const files = (await readdir(schemaDir, { recursive: true }))
  .filter((f) => f.endsWith('.schema.json'))
  .sort();

const bundle = {
  title: 'Contracts',
  description: 'Index of every contract; exists only so all schemas compile in one pass.',
  type: 'object',
  additionalProperties: false,
  properties: Object.fromEntries(
    files.map((f) => [f.split('/').pop().replace('.schema.json', ''), { $ref: `./${f}` }]),
  ),
};

const ts = await compile(bundle, 'Contracts', {
  cwd: schemaDir,
  additionalProperties: false,
  unreachableDefinitions: true,
  bannerComment: `/* GENERATED by scripts/gen_ts.mjs from ${relative(root, schemaDir)}/. Do not edit; run \`make types\`. */`,
});

await mkdir(outDir, { recursive: true });
await writeFile(join(outDir, 'index.ts'), ts);
console.log(`wrote ${relative(root, join(outDir, 'index.ts'))} from ${files.length} schemas`);
