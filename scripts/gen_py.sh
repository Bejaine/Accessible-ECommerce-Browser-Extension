#!/usr/bin/env bash
# Regenerate Pydantic v2 models in shared/generated/py/contracts/ from shared/schemas/.
set -euo pipefail
cd "$(dirname "$0")/.."
PY=${PY:-.venv/bin}
out=shared/generated/py/contracts
rm -rf "$out"
"$PY/datamodel-codegen" \
  --input shared/schemas \
  --input-file-type jsonschema \
  --output "$out" \
  --output-model-type pydantic_v2.BaseModel \
  --target-python-version 3.11 \
  --use-title-as-name \
  --use-standard-collections \
  --use-union-operator \
  --field-constraints \
  --use-schema-description \
  --disable-timestamp \
  --formatters builtin \
  --custom-file-header "# GENERATED by scripts/gen_py.sh from shared/schemas/. Do not edit; run \`make types\`."
"$PY/ruff" format --quiet "$out"
